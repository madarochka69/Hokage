x1 = float(input("Введите первую точку:"))
y1 = float(input("Введите второю точку:"))
x2 = float(input("Введите третью точку:"))
y2 = float(input("Введите четвертую точку:"))
x3 = float(input("Введите пятую точку:"))
y3 = float(input("Введите шестую точку:"))
a = ((x2 - x1) ** 2 + (y2 - y1) ** 2) ** 0.5
b = ((x3 - x2) ** 2 + (y3 - y2) ** 2) ** 0.5
c = ((x1 - x3) ** 2 + (y1 - y3) ** 2) ** 0.5
P = (a + b + c) / 2 
S = (P *(P - a) * (P - b) * (P - c)) ** 0.5
print(f"Периметр = {P}")
print(f"Площадь = {S}")